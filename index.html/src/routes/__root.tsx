function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // Reminder notification clicks (from the service worker) open the dashboard.
  useEffect(() => {
    if (!("serviceWorker" in navigator)) return;
    const onMessage = (event: MessageEvent) => {
      const data = event.data as { type?: string; habitId?: string; action?: string } | undefined;
      if (data?.type !== "BTY_REMINDER_CLICK") return;
      const url = new URL("/dashboard", window.location.origin);
      if (data.habitId) url.searchParams.set("habit", data.habitId);
      if (data.action) url.searchParams.set("action", data.action);
      window.location.assign(url.toString());
    };
    navigator.serviceWorker.addEventListener("message", onMessage);
    return () => navigator.serviceWorker.removeEventListener("message", onMessage);
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
